Map<String, City>? _index;

String _key(String s) => s
    .split(',')
    .first
    .toLowerCase()
    .replaceAll(RegExp(r'\(.*?\)'), '')
    .replaceAll(RegExp(r'[^a-z0-9 ]'), ' ')
    .replaceAll(RegExp(r'\s+'), ' ')
    .trim();

/// Finds a built-in city by name or common alias. Null when unknown.
City? findCity(String name) {
  _index ??= {for (final c in kCities) _key(c.name): c};
  var k = _key(name);
  if (k.isEmpty) return null;
  k = kAliases[k] ?? k;
  return _index![k];
}
